//! Sparkplug B 3.0 payload codec for the opencap edge node (#51).
//!
//! What a Sparkplug message looks like is specified in `docs/spec/payload-sparkplug.md`; this
//! crate implements that page and nothing that needs a broker or the tag store:
//!
//! - [`topic`]: the `spBv1.0/...` namespace, built and parsed, ids validated;
//! - [`datatype`]: opencap dtype -> Sparkplug datatype, value encoding (scalars and packed arrays);
//! - [`quality`]: the ADR-0006 Sparkplug column (`Quality` property, null values);
//! - [`message`]: NBIRTH / NDEATH / DBIRTH / DDATA / DDEATH payloads, metric names and
//!   aliases, `seq` and `bdSeq`;
//! - [`command`]: NCMD / DCMD classification: only `Node Control/Rebirth` is honoured, every
//!   other command is rejected (read-only, ADR-0008);
//! - [`state`]: the primary host's `spBv1.0/STATE/<host_id>` payload.
//!
//! The language-neutral vectors in `tests/conformance/sparkplug/` (generated by an independent
//! Python reference on Google's protobuf runtime) are checked by `tests/vectors.rs`.

pub mod command;
pub mod datatype;
pub mod message;
pub mod proto;
pub mod quality;
pub mod state;
pub mod topic;

pub use proto::payload::Metric;
pub use proto::{DataType, Payload};

/// A payload or topic opencap cannot build or does not accept.
#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
#[error("{0}")]
pub struct CodecError(pub String);

impl CodecError {
    pub(crate) fn new(msg: impl Into<String>) -> Self {
        CodecError(msg.into())
    }
}
