"""Config loader (PLAN.md section 8).

`load_config(config_dir)` reads:

- `poller.yaml`       optional, global settings (missing -> `PollerConfig()` defaults)
- `devices.json`      required, generated by `opencap import-kep`
- `overrides.yaml`    optional, hand fixes per channel / device / tag
- `devices_map.yaml`  optional, SubDeviceId / topic / env per device

and returns validated models. Order of application for a device:

1. `devices.json`
2. `overrides.yaml` device fields, `params` (dict merge) and per-tag fields
3. publish settings, lowest priority first: devices.json `publish` ->
   `devices_map.yaml` `defaults` -> `overrides.yaml` `publish` ->
   `devices_map.yaml` entry (`sub_device_id`, `topic`, `env`)
4. `publish.topic` still unset -> `default_topic(device, poller.mqtt.topic_prefix)`
5. serial drivers (`ab_df1`, `modbus_rtu`) still at `transport: unmapped` -> `overrides.yaml`
   `serial_ports[<params.com_port>]` sets transport, host and port; with no mapping the device is
   disabled with a warning (it cannot be reached). The resulting endpoint is validated.

Unknown channel names, device ids and tag names in `overrides.yaml` / `devices_map.yaml`
are warnings, not errors. Invalid values are errors (pydantic `ValidationError`).
"""

from __future__ import annotations

import json
import re
import unicodedata
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

import yaml

from opencap.config.models import (
    name_rule_problems,
    underscore_names,
    DEFAULT_TOPIC_PREFIX,
    Channel,
    Device,
    DeviceMap,
    DevicesFile,
    ExcludedDevice,
    Overrides,
    PollerConfig,
    PublishCfg,
)

POLLER_FILE = "poller.yaml"
DEVICES_FILE = "devices.json"
MAP_FILE = "devices_map.yaml"
OVERRIDES_FILE = "overrides.yaml"

_LIST_LIMIT = 5          # ids listed in an aggregate warning
_PUBLISH_FIELDS = set(PublishCfg.model_fields)
_DEVICE_SCALARS = (
    "enabled", "host", "port", "scan_ms", "min_scan_ms", "timeout_ms", "retries",
    "demote_after", "demote_for_ms",
)
_TAG_FIELDS = ("enabled", "address", "dtype", "scan_ms", "scale")
SERIAL_DRIVERS: dict[str, tuple[str, ...]] = {        # driver -> transports it supports
    "ab_df1": ("tcp", "serial", "rfc2217"),
    "modbus_rtu": ("tcp", "serial"),
}


@dataclass
class LoadedConfig:
    poller: PollerConfig
    channels: list[Channel]
    excluded: list[ExcludedDevice] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)


def slug(s: str) -> str:
    """MQTT-safe topic level: lowercase ASCII, runs of anything but [a-z0-9._-] -> '_'.

    No '+', '#', '/', spaces or leading '$' can survive. 'Site 001' -> 'site_001',
    'E+H' -> 'e_h'. Never returns an empty string.
    """
    ascii_ = unicodedata.normalize("NFKD", s).encode("ascii", "ignore").decode("ascii")
    out = re.sub(r"[^a-z0-9._-]+", "_", ascii_.lower()).strip("_")
    return out or "_"


def default_topic(device: Device, prefix: str = DEFAULT_TOPIC_PREFIX) -> str:
    """`<prefix>/<slug(channel)>/<slug(device)>/data`; `prefix` is poller.yaml `mqtt.topic_prefix`."""
    return f"{prefix}/{slug(device.channel)}/{slug(device.name)}/data"


def _ids(ids: list[str]) -> str:
    shown = ", ".join(ids[:_LIST_LIMIT])
    return shown + (f", … (+{len(ids) - _LIST_LIMIT} more)" if len(ids) > _LIST_LIMIT else "")


def _read_yaml(path: Path) -> dict[str, Any]:
    """Missing file -> {}; empty file -> {}; top level must be a mapping."""
    if not path.exists():
        return {}
    try:
        data = yaml.safe_load(path.read_text(encoding="utf-8"))
    except yaml.YAMLError as exc:
        raise ValueError(f"{path}: invalid YAML: {exc}") from exc
    if data is None:
        return {}
    if not isinstance(data, dict):
        raise ValueError(f"{path}: top level must be a mapping, got {type(data).__name__}")
    return data


def _load_devices(path: Path) -> DevicesFile:
    if not path.exists():
        raise FileNotFoundError(f"{path} not found: run `opencap import-kep project.json` first")
    try:
        data = json.loads(path.read_text(encoding="utf-8-sig"))
    except json.JSONDecodeError as exc:
        raise ValueError(f"{path}: invalid JSON: {exc}") from exc
    return DevicesFile.model_validate(data)


def _apply_device_override(dev: dict[str, Any], ov: Any, warnings: list[str]) -> dict[str, Any]:
    """Return the publish dict from the override (applied later); mutate `dev` for the rest."""
    for name in _DEVICE_SCALARS:
        value = getattr(ov, name)
        if value is not None:
            dev[name] = value
    if ov.params:
        dev["params"] = {**dev.get("params", {}), **ov.params}
    if ov.tags:
        by_name = {t["name"]: t for t in dev["tags"]}
        for tag_name, tov in ov.tags.items():
            tag = by_name.get(tag_name)
            if tag is None:
                warnings.append(f"{OVERRIDES_FILE}: device {dev['id']!r} has no tag {tag_name!r}; override ignored")
                continue
            for name in _TAG_FIELDS:
                value = getattr(tov, name)
                if value is not None:
                    tag[name] = value.model_dump() if name == "scale" else value
    return dict(ov.publish)


def _serial_mapping(ports: dict[str, str], com: Any) -> tuple[str, str] | None:
    """(key as written, target) for a COM port name, case-insensitive."""
    if not com:
        return None
    wanted = str(com).strip().upper()
    for key, target in ports.items():
        if key.strip().upper() == wanted:
            return key, target
    return None


def _resolve_serial(dev: dict[str, Any], ports: dict[str, str], used: set[str], warnings: list[str]) -> None:
    """Map an unmapped serial device's COM port (overrides.yaml serial_ports), or disable it."""
    from opencap.drivers._serial import parse_port_mapping

    params = dev.setdefault("params", {})
    if str(params.get("transport") or "tcp").strip().lower() != "unmapped":
        return
    com = params.get("com_port")
    hit = _serial_mapping(ports, com)
    if hit is None:
        if dev.get("enabled", True):
            where = com or "its serial port"
            warnings.append(
                f"{dev['id']}: {where} is not mapped to a transport (transport: unmapped); device skipped. "
                f"Map it in {OVERRIDES_FILE} serial_ports, e.g. {com or 'COM1'}: 192.0.2.50:4001")
        dev["enabled"] = False
        return
    key, target = hit
    used.add(key)
    try:
        kind, host, port = parse_port_mapping(target)
    except ValueError as exc:
        raise ValueError(f"{OVERRIDES_FILE}: serial_ports {key}: {exc}") from None
    params["transport"] = kind
    dev["host"], dev["port"] = host, port


def _check_serial_endpoint(device: Device) -> None:
    from opencap.drivers._serial import TransportUnmapped, endpoint_for

    try:
        endpoint_for(device, allowed=SERIAL_DRIVERS[device.driver])
    except TransportUnmapped:
        pass
    except ValueError as exc:
        raise ValueError(f"{device.id}: {exc}") from None


def sparkplug_device_id(poller: PollerConfig, device: Device) -> str:
    """The Sparkplug device id of an opencap device: `sparkplug.devices`, else `<channel>.<device>`."""
    return poller.sparkplug.devices.get(device.id, f"{device.channel}.{device.name}")


def _sparkplug_checks(poller: PollerConfig, channels: list[Channel]) -> list[str]:
    """Cross-file rules of `sparkplug` (#51). Errors only while it is enabled."""
    from opencap.config.models import _sparkplug_id_error

    cfg = poller.sparkplug
    ids = {d.id for c in channels for d in c.devices}
    warnings = [f"{POLLER_FILE}: sparkplug.devices: unknown device id {dev!r}; entry ignored"
                for dev in cfg.devices if dev not in ids]
    if not cfg.enabled:
        return warnings
    seen: dict[str, str] = {}
    for c in channels:
        for d in c.devices:
            if not d.enabled:
                continue
            sp = sparkplug_device_id(poller, d)
            if err := _sparkplug_id_error(f"device id of {d.id!r}", sp):
                raise ValueError(f"{POLLER_FILE}: {err}; map it in sparkplug.devices")
            if sp in seen:
                raise ValueError(f"{POLLER_FILE}: sparkplug: {seen[sp]!r} and {d.id!r} both get the Sparkplug "
                                 f"device id {sp!r}; map one in sparkplug.devices")
            seen[sp] = d.id
    return warnings


def load_config(config_dir: Path) -> LoadedConfig:
    config_dir = Path(config_dir)
    warnings: list[str] = []

    poller = PollerConfig.model_validate(_read_yaml(config_dir / POLLER_FILE))
    devices_file = _load_devices(config_dir / DEVICES_FILE)
    overrides = Overrides.model_validate(_read_yaml(config_dir / OVERRIDES_FILE))
    map_path = config_dir / MAP_FILE
    device_map = DeviceMap.model_validate(_read_yaml(map_path))

    known_channels = {c.name for c in devices_file.channels}
    known_devices = {d.id for c in devices_file.channels for d in c.devices}

    for name, settings in overrides.channels.items():
        if name not in known_channels:
            warnings.append(f"{OVERRIDES_FILE}: unknown channel {name!r}; override ignored")
        for key in settings:
            if key != "enabled":
                warnings.append(f"{OVERRIDES_FILE}: channel {name!r}: unknown setting {key!r} ignored")
    for dev_id in overrides.devices:
        if dev_id not in known_devices:
            warnings.append(f"{OVERRIDES_FILE}: unknown device id {dev_id!r}; override ignored")
    for dev_id in device_map.devices:
        if dev_id not in known_devices:
            warnings.append(f"{MAP_FILE}: unknown device id {dev_id!r}; entry ignored")

    map_defaults = {}
    for key, value in device_map.defaults.items():
        if key in _PUBLISH_FIELDS:
            map_defaults[key] = value
        else:
            warnings.append(f"{MAP_FILE}: defaults.{key} is not a publish setting; ignored")

    channels: list[Channel] = []
    unmapped: list[str] = []
    stubs: list[str] = []
    serial_used: set[str] = set()
    for ch in devices_file.channels:
        ch_enabled = ch.enabled
        ch_ov = overrides.channels.get(ch.name)
        if ch_ov is not None and "enabled" in ch_ov:
            ch_enabled = bool(ch_ov["enabled"])
        devices: list[Device] = []
        for device in ch.devices:
            dev = device.model_dump()
            publish = dict(dev.get("publish") or {})
            publish.update(map_defaults)
            ov = overrides.devices.get(device.id)
            if ov is not None:
                ov_publish = _apply_device_override(dev, ov, warnings)
                publish.update(ov_publish)
            entry = device_map.devices.get(device.id)
            if entry is None:
                unmapped.append(device.id)
            else:
                if entry.stub:
                    stubs.append(device.id)
                publish["sub_device_id"] = entry.sub_device_id
                for key in ("topic", "env"):
                    value = getattr(entry, key)
                    if value is None:
                        continue
                    if ov is not None and key in ov.publish and ov.publish[key] != value:
                        warnings.append(
                            f"{device.id}: publish.{key} set in both {OVERRIDES_FILE} and {MAP_FILE}; "
                            f"using {MAP_FILE}"
                        )
                    publish[key] = value
            dev["publish"] = publish
            if dev.get("driver") in SERIAL_DRIVERS:
                _resolve_serial(dev, overrides.serial_ports, serial_used, warnings)
            new = Device.model_validate(dev)
            if new.driver in SERIAL_DRIVERS:
                _check_serial_endpoint(new)
            if new.publish.topic is None:
                new.publish.topic = default_topic(new, poller.mqtt.topic_prefix)
            devices.append(new)
        channels.append(Channel(name=ch.name, enabled=ch_enabled, devices=devices))

    for key in overrides.serial_ports:
        if key not in serial_used:
            warnings.append(f"{OVERRIDES_FILE}: serial_ports {key} is not used by any unmapped serial device")

    if unmapped:
        where = f"{MAP_FILE} is missing" if not map_path.exists() else f"no entry in {MAP_FILE}"
        warnings.append(f"{len(unmapped)} device(s) without SubDeviceId ({where}): {_ids(unmapped)}")
    if stubs:
        warnings.append(
            f"{len(stubs)} device(s) use a stub SubDeviceId (stub: true in {MAP_FILE}); "
            f"confirm before go-live: {_ids(stubs)}"
        )

    all_devices = [d for c in channels for d in c.devices]
    for what, attr in (("MQTT topic", "topic"), ("SubDeviceId", "sub_device_id")):
        users: dict[str, list[str]] = {}
        for d in all_devices:
            value = getattr(d.publish, attr)
            if value:
                users.setdefault(value, []).append(d.id)
        for value, ids in users.items():
            if len(ids) > 1:
                warnings.append(f"{what} {value!r} is used by {len(ids)} devices: {_ids(ids)}")

    if devices_file.version < 2:      # names starting with '_' are an error from v2 on (spec 3.2)
        warnings += [f"{DEVICES_FILE}: {text}; names starting with '_' are reserved for system tags"
                     for text in underscore_names(channels)]
        warnings += [f"{DEVICES_FILE}: {text}" for _, text in name_rule_problems(channels)]

    warnings.extend(_sparkplug_checks(poller, channels))

    # Final pass through the models (cheap, and catches cross-field rules).
    validated = DevicesFile(
        version=devices_file.version,
        generated_from=devices_file.generated_from,
        generated_at=devices_file.generated_at,
        channels=channels,
        excluded=devices_file.excluded,
    )
    return LoadedConfig(
        poller=poller,
        channels=validated.channels,
        excluded=list(validated.excluded),
        warnings=warnings,
    )
