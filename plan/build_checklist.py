"""Build plan/checklist.md from the "Checklist rows" table at the end of every plan/features/*.md.

    python plan/build_checklist.py            # rewrite plan/checklist.md
    python plan/build_checklist.py --check    # exit 1 if checklist.md is out of date

Edit the feature files, never checklist.md by hand.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

PLAN = Path(__file__).resolve().parent
FEATURES = PLAN / "features"
OUT = PLAN / "checklist.md"
STATUSES = ("Done", "In review", "Planned", "Not started", "Out of scope")
COLUMNS = ("ID", "Feature", "Decision", "Status", "Issue/PR", "Milestone")


def status_class(status: str) -> str:
    for s in STATUSES:
        if status.strip().lower().startswith(s.lower()):
            return s
    return "Other"


def rows(path: Path) -> tuple[str, list[dict[str, str]]]:
    text = path.read_text(encoding="utf-8")
    title = next((ln[2:].strip() for ln in text.splitlines() if ln.startswith("# ")), path.stem)
    section = text.split("## Checklist rows", 1)
    if len(section) < 2:
        raise SystemExit(f"{path.name}: no '## Checklist rows' section")
    out = []
    for line in section[1].splitlines():
        line = line.strip()
        if not line.startswith("|") or re.match(r"^\|\s*-", line):
            continue
        cells = [c.strip() for c in line.strip("|").split("|")]
        if cells[0] == "ID":
            continue
        cells += [""] * (len(COLUMNS) - len(cells))
        out.append(dict(zip(COLUMNS, cells[: len(COLUMNS)], strict=True)))
    return title, out


def render() -> str:
    areas = [(p, *rows(p)) for p in sorted(FEATURES.glob("[0-9][0-9]-*.md"))]
    head = ["# Checklist", "",
            "Every feature of the KEPServerEX V6 server manual, as planned in [`features/`](features/).",
            "Generated by `python plan/build_checklist.py` from the **Checklist rows** table at the end",
            "of each feature file: edit the feature file, then re-run the script. `[x]` = done,",
            "`[ ]` = to do, ~~struck~~ = out of scope (the feature file says why).", "",
            "## Summary", "",
            "| Area | Features | " + " | ".join(STATUSES) + " |",
            "|---|---:|" + "---:|" * len(STATUSES)]
    body: list[str] = []
    totals = dict.fromkeys(STATUSES, 0)
    total = 0
    for path, title, items in areas:
        counts = dict.fromkeys(STATUSES, 0)
        body += ["", f"## [{title}](features/{path.name})", ""]
        for r in items:
            cls = status_class(r["Status"])
            if cls in counts:
                counts[cls] += 1
            extra = " · ".join(x for x in (r["Decision"], r["Status"], r["Issue/PR"], r["Milestone"])
                               if x and x not in {"—", "-"})
            label = f"**{r['ID']}** {r['Feature']}"
            if cls == "Out of scope":
                body.append(f"- ~~{r['ID']} {r['Feature']}~~ ({extra})")
            else:
                body.append(f"- [{'x' if cls == 'Done' else ' '}] {label} ({extra})")
        n = len(items)
        total += n
        for s in STATUSES:
            totals[s] += counts[s]
        head.append(f"| [{title}](features/{path.name}) | {n} | " + " | ".join(str(counts[s]) for s in STATUSES) + " |")
    head.append(f"| **Total** | **{total}** | " + " | ".join(f"**{totals[s]}**" for s in STATUSES) + " |")
    return "\n".join(head + body) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail if checklist.md is out of date")
    args = ap.parse_args(argv)
    text = render()
    if args.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("plan/checklist.md is out of date: run python plan/build_checklist.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(PLAN.parent)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
