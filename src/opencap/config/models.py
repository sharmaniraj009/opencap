    api: ApiCfg = Field(default_factory=ApiCfg)
    payload: PayloadCfg = Field(default_factory=PayloadCfg)
    defaults: DeviceDefaults = Field(default_factory=DeviceDefaults)
    check: CheckCfg = Field(default_factory=CheckCfg)
